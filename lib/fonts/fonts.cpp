#include "fonts.h"

Number8x16::Number8x16(Display& display)
: m_display{display}
{
}

void Number8x16::draw_char(char c, int16_t x_start, int16_t y_start)
{
    size_t offset{0};

    if (c >= '0' && c <= '9') {
        offset = c - '0'; // '0' -> ASCI #48
    }
    else if (c == '.') {
        offset = 10;
    }
    else if (c == 'C') {
        offset = 11;
    }
    else if (c == '%') {
        offset = 12;
    }
    else if (c == 'h') {
        offset = 13;
    }
    else if (c == 'm') {
        offset = 14;
    }
    else if (c == 's') {
        offset = 15;
    }
    else if (c == '>') {
        offset = 16;
    }
    else if (c == ':') {
        offset = 17;
    }
    else {
        // skip unknown characters
        return;
    }

    m_display.draw_bitmap(x_start, y_start, Bitmap{8, 16, (const uint8_t*) (NUMBER_8_16 + 16 * (((uint8_t) offset)))});
}

void Number8x16::draw(const char* s, int16_t x, int16_t y, char h_alignment)
{
    int16_t x_char = x;
    uint8_t n_chars = 0;

    for (uint8_t i = 0; s[i] != '\0'; i++) {
        n_chars += 1;
        if (h_alignment == 'l') {
            draw_char(s[i], x_char, y);
        }
        if (s[i + 1] == '.' || s[i] == '.' || s[i + 1] == ' ' || s[i] == ' ' || s[i + 1] == ':' || s[i] == ':') {
            // less horizontal space for '.' and ' '
            x_char += 6; // as decreased by 2 before and after, total width is 4
        }
        else {
            x_char += 8;
        }
    }

    if (h_alignment == 'r') {
        x_char = x;
        for (uint8_t i = n_chars; i > 0; i--) {
            if (s[i] == '.' || s[i - 1] == '.' || s[i] == ' ' || s[i - 1] == ' ' || s[i] == ':' || s[i - 1] == ':') {
                // less horizontal space for '.' and ' '
                x_char -= 6; // as decreased by 2 before and after, total width is 4
            }
            else {
                x_char -= 8;
            }
            draw_char(s[i - 1], x_char, y);
        }
    }
}

Number18x32::Number18x32(Display& display)
: m_display{display}
{
}

void Number18x32::draw_char(char c, int16_t x_start, int16_t y_start)
{
    size_t offset{0};

    if (c >= '0' && c <= '9') {
        offset = c - '0'; // '0' -> ASCI #48
        m_display.draw_bitmap(x_start, y_start, Bitmap{18, 32, DIGITS_18_32[offset]});
    }
    else if (c == '.') {
        offset = 10;
        m_display.draw_bitmap(x_start, y_start + 26, Bitmap{18, 6, DOT_18_6});
    }
    else if (c == ':') {
        m_display.draw_bitmap(x_start, y_start + 5, Bitmap{18, 6, DOT_18_6});
        m_display.draw_bitmap(x_start, y_start + 21, Bitmap{18, 6, DOT_18_6});
    }
    else if (c == '-') {
        m_display.draw_bitmap(x_start, y_start + (int16_t) 14, Bitmap{18, 4, DASH_18_4});
    }
    else if (c == '%') {
        m_display.draw_bitmap(x_start, y_start, Bitmap{19, 22, CHARS_16_22[0]});
    }
    else if (c == 'C') {
        m_display.draw_bitmap(x_start, y_start, Bitmap{19, 22, CHARS_16_22[1]});
    }
    else if (c == '#') {
        m_display.draw_bitmap(x_start, y_start, Bitmap{19, 22, CHARS_16_22[2]});
    }
    else if (c == 'h') {
        m_display.draw_bitmap(x_start, y_start, Bitmap{19, 22, CHARS_16_22[3]});
    }
    else if (c == 'm') {
        m_display.draw_bitmap(x_start, y_start, Bitmap{19, 22, CHARS_16_22[4]});
    }
    else if (c == 's') {
        m_display.draw_bitmap(x_start, y_start, Bitmap{19, 22, CHARS_16_22[5]});
    }
    else {
        // skip unknown characters
        return;
    }
}

void Number18x32::draw(const char* s, int16_t x, int16_t y, char h_alignment)
{
    int16_t x_char = x;
    uint8_t n_chars = 0;

    for (uint8_t i = 0; s[i] != '\0'; i++) {
        n_chars += 1;
        if (h_alignment == 'l') {
            draw_char(s[i], x_char, y);
        }
        if (s[i + 1] == '.' || s[i] == '.' || s[i + 1] == ':' || s[i] == ':') {
            // less horizontal space before and after '.' and ':'
            x_char += 14;
        }
        else if (s[i] == ' ') {
            // less horizontal space for ' '
            x_char += 8;
        }
        else if (s[i] == 'C' || s[i] == '%' || s[i] == '#' || s[i] == 'h' || s[i] == 'm' || s[i] == 's') {
            // different horizontal space for units, most 16px except for 'm' 19px
            x_char += 19;
        }
        else {
            x_char += 20;
        }
    }

    if (h_alignment == 'c') {
        x_char = -(x_char - x) / 2;
        for (uint8_t i = 0; i < n_chars; i++) {
            draw_char(s[i], x + x_char, y);
            if (s[i + 1] == '.' || s[i] == '.' || s[i + 1] == ':' || s[i] == ':') {
                // less horizontal space for '.' and ':'
                x_char += 14;
            }
            else if (s[i] == ' ') {
                // less horizontal space for ' '
                x_char += 8;
            }
            else if (s[i] == 'C' || s[i] == '%' || s[i] == '#' || s[i] == 'h' || s[i] == 'm' || s[i] == 's') {
                // different horizontal space for units, most 16px except for 'm' 19px
                x_char += 19;
            }
            else {
                x_char += 20;
            }
        }
        return;
    }

    if (h_alignment == 'r') {
        x_char = x;
        for (uint8_t i = n_chars; i > 0; i--) {
            if (s[i] == '.' || s[i - 1] == '.' || s[i] == ':' || s[i - 1] == ':') {
                // less horizontal space for '.' and ':'
                x_char -= 14;
            }
            else if (s[i] == ' ') {
                // less horizontal space for ' '
                x_char -= 8;
            }
            else if (s[i] == 'C' || s[i] == '%' || s[i] == '#' || s[i] == 'h' || s[i] == 'm' || s[i] == 's') {
                // different horizontal space for units, most 16px except for 'm' 19px
                x_char -= 19;
            }
            else {
                x_char -= 20;
            }
            draw_char(s[i - 1], x_char, y);
        }
    }
}

